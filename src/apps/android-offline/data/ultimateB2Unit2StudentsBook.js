export function applyUltimateB2Unit2StudentsBookAndroidOverlay(bookPackage) {
  return {
    ...bookPackage,
    components: (bookPackage.components || []).map((component) => {
      if (component.id !== "students-book") return component;

      return {
        ...component,
        units: (component.units || []).map((unit) => (
          unit.id === "sb-unit-2"
            ? { ...unit, lessons: ultimateB2Unit2StudentsBookLessons }
            : unit
        )),
      };
    }),
  };
}
