export function runtimeSchemaContractData(migrations) {
  const summary = migrationManifestSummary(migrations);
  return {
    version: 1,
    expectedMigrationCount: summary.migrationCount,
    latestMigration: summary.latestMigration,
    manifestFingerprint: summary.manifestFingerprint,
    expectedMigrations: migrations.map(({ filename, compatibleChecksums }) => ({
      filename,
      compatibleChecksums: [...compatibleChecksums].sort(),
    })),
    requiredTables: Object.entries(requiredRuntimeSchema).map(([table, columns]) => ({
      table,
      columns,
    })),
  };
}

export function renderRuntimeSchemaContract(contract) {
  return [
    "// Generated by scripts/generate-runtime-schema-contract.mjs. Do not edit manually.",
    `export const runtimeSchemaContract = Object.freeze(${JSON.stringify(contract, null, 2)});`,
    "",
  ].join("\n");
}

export async function expectedRuntimeSchemaContractSource() {
  const migrations = await loadProductionMigrationManifest();
  return renderRuntimeSchemaContract(runtimeSchemaContractData(migrations));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const source = await expectedRuntimeSchemaContractSource();
  await writeFile(runtimeSchemaContractUrl, source, "utf8");
  const contract = runtimeSchemaContractData(await loadProductionMigrationManifest());
  console.log(
    `Runtime schema contract generated: ${contract.expectedMigrationCount} migrations; latest ${contract.latestMigration}; fingerprint ${contract.manifestFingerprint}.`,
  );
}
