import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { expect } from "@playwright/test";
import { publicationV2Fixture } from "../fixtures/publication-v2.js";

export async function verifyStudentsBookWorkflow({ pool, page, teacherContext, login, origin, teacher, student, books, publishNewer }) {
  const api = (action) => `${origin}/.netlify/functions/book-content?action=${action}`;
  const book = books.find((entry) => entry.componentSlug === "ultimate-b2-students-book");
  const target = book.pages[0].hotspots.find((entry) => entry.target?.nativeActivityId === publicationV2Fixture.openResponseId).target;
  const qa = (await pool.query("insert into book_packages(publisher_id,title,slug,level,status) select publisher_id,'Isolated QA Book','isolated-browser-qa-book','B2','active' from book_packages where id=$1 returning id,title", [book.packageId])).rows[0];
  await pool.query("insert into book_access(user_id,book_package_id,role_scope) values($1,$2,'teacher')", [teacher.id, qa.id]);
  await page.goto(`${origin}/#/teacher/classes`);
  await page.reload();
  await expect(page.getByRole("button", { name: "Create class", exact: true })).toBeDisabled();
  await page.getByLabel("Class name", { exact: true }).fill("Compatible browser B2");
  await page.locator(".teacher-create-class-form select").nth(1).selectOption(qa.id);
  await page.locator(".teacher-create-class-form select").nth(1).selectOption(book.packageId);
  await page.getByRole("button", { name: "Create class", exact: true }).click();
  await expect(page.getByText("Class created. Share the invite link with students.", { exact: true })).toBeVisible();
  const compatible = (await pool.query("select id,book_package_id,assigned_book,invite_code from classes where teacher_id=$1 and name='Compatible browser B2'", [teacher.id])).rows[0];
  assert.equal(compatible.book_package_id, book.packageId);
  assert.equal(compatible.assigned_book, book.packageTitle);
  const studentContext = await login(student);
  const join = await studentContext.request.post(api("join-class"), { data: { inviteCode: compatible.invite_code } });
  assert.equal(join.status(), 200, await join.text());
  const incompatibleResponse = await teacherContext.request.post(api("create-class"), { data: { name: "Incompatible browser QA", level: "B2", bookPackageId: qa.id, assignedBook: qa.title } });
  assert.equal(incompatibleResponse.status(), 200, await incompatibleResponse.text());
  const incompatible = (await incompatibleResponse.json()).classItem;
  const forged = await teacherContext.request.post(api("create-assignment"), { data: { title: "Forbidden mismatch", idempotencyKey: randomUUID(), classIds: [incompatible.id], target } });
  assert.equal(forged.status(), 409, await forged.text());
  assert.equal((await forged.json()).conflict, "class-package-mismatch");

  const imageQuery = new URLSearchParams({ action: "published-page-image", bookSlug: book.bookSlug, componentSlug: book.componentSlug, releaseId: book.releaseId, pageId: book.pages[0].id, sha256: book.pages[0].image.checksumSha256 });
  const imageUrl = `${origin}/.netlify/functions/book-content?${imageQuery}`;
  assert.equal((await fetch(imageUrl)).status, 401);
  const unentitled = (await pool.query("insert into app_users(school_id,full_name,role,status) values($1,'Unentitled browser student','student','active') returning id", [teacher.school_id])).rows[0];
  const unentitledContext = await login(unentitled);
  assert.equal((await unentitledContext.request.get(imageUrl)).status(), 403);
  // Membership alone must not grant the learner the book.
  assert.equal((await unentitledContext.request.post(api("join-class"), { data: { inviteCode: compatible.invite_code } })).status(), 200);
  assert.equal((await unentitledContext.request.get(imageUrl)).status(), 403);
  await pool.query("insert into book_access(user_id,book_package_id,role_scope) values($1,$2,'student')", [unentitled.id, book.packageId]);
  assert.equal((await unentitledContext.request.get(imageUrl)).status(), 200);
  await pool.query("delete from book_access where user_id=$1 and book_package_id=$2", [unentitled.id, book.packageId]);
  assert.equal((await unentitledContext.request.get(imageUrl)).status(), 403);

  await page.goto(`${origin}/#/teacher/assignments`);
  await page.reload();
  const picker = page.getByRole("region", { name: "Choose exercises from published pages" });
  await picker.locator(":scope > label > select").selectOption(book.componentSlug);
  const hotspot = picker.locator(".published-page-hotspots").getByRole("button", { name: "Native Open Response", exact: true });
  await hotspot.click();
  await picker.getByRole("button", { name: "Add exercise", exact: true }).click();
  await page.route(imageUrl, (route) => route.fulfill({ status: 503, body: "Unavailable" }));
  await picker.getByRole("button", { name: "Next page", exact: true }).click();
  await picker.getByRole("button", { name: "Previous page", exact: true }).click();
  await expect(picker.getByRole("alert")).toContainText("Page image is unavailable");
  await page.unroute(imageUrl);
  await picker.getByRole("button", { name: "Retry page image", exact: true }).click();
  await expect.poll(() => picker.locator('.published-page > img').evaluate((image) => image.complete && image.naturalWidth > 1)).toBe(true);
  await picker.locator(".published-page-hotspots").getByRole("button", { name: "Native Open Response · selected", exact: true }).click();
  const creator = page.locator(".homework-creator");
  await creator.getByLabel("Homework title", { exact: true }).fill("Students Book browser assignment");
  for (const checkbox of await creator.locator('.teacher-checkbox-panel input').all()) await checkbox.uncheck();
  await creator.getByLabel("Incompatible browser QA", { exact: true }).check();
  await expect(creator.getByRole("button", { name: "Create assignment", exact: true })).toBeDisabled();
  await expect(picker.locator(".homework-class-compatibility")).toContainText("incompatible");
  await expect(creator.locator(".homework-selected-activities")).toContainText("Selected activities (1)");
  await creator.getByLabel("Incompatible browser QA", { exact: true }).uncheck();
  await creator.getByLabel("Compatible browser B2", { exact: true }).check();
  await expect(creator.getByRole("button", { name: "Create assignment", exact: true })).toBeEnabled();
  await picker.getByRole("button", { name: "Preview exercise", exact: true }).click();
  await expect(page.getByRole("dialog").getByRole("textbox").first()).toBeEditable();
  await page.getByRole("dialog").getByRole("textbox").first().fill("Preview only");
  await page.getByRole("button", { name: "Close preview", exact: true }).click();
  const before = Number((await pool.query("select count(*) from activity_submissions where student_id=$1", [student.id])).rows[0].count);
  await creator.getByRole("button", { name: "Create assignment", exact: true }).click();
  await expect(creator.locator(".homework-selected-activities")).toContainText("Selected activities (0)");
  const assignment = (await pool.query("select id,native_release_id,native_activity_id,native_book_locator from activity_assignments where teacher_id=$1 and class_id=$2 and title='Students Book browser assignment'", [teacher.id, compatible.id])).rows[0];
  assert.ok(assignment, "Compatible class assignment persisted");
  assert.equal(assignment.native_release_id, target.releaseId);
  assert.equal(assignment.native_activity_id, target.nativeActivityId);
  assert.deepEqual(assignment.native_book_locator, target.locator);
  assert.equal(Number((await pool.query("select count(*) from activity_submissions where student_id=$1", [student.id])).rows[0].count), before);
  await publishNewer();
  const studentPage = await studentContext.newPage();
  await studentPage.goto(`${origin}/#/student/assignments/${assignment.id}`);
  await expect(studentPage.locator('[data-book-mode="assigned"]')).toHaveAttribute("data-release-id", target.releaseId);
  await expect.poll(() => studentPage.locator('.published-page > img').evaluate((image) => image.complete && image.naturalWidth > 1)).toBe(true);
  await studentPage.getByRole("textbox").first().fill("Students Book final response");
  await studentPage.getByRole("button", { name: "Submit assignment", exact: true }).click();
  await studentPage.getByRole("button", { name: "Submit final answers", exact: true }).click();
  await expect(studentPage.getByRole("button", { name: "Submit assignment", exact: true })).toHaveCount(0);
  await studentPage.reload();
  await expect(studentPage.getByRole("textbox").first()).toHaveValue("Students Book final response");
  await expect(studentPage.getByRole("textbox").first()).not.toBeEditable();
  await expect(studentPage.locator('[data-book-mode="assigned"]')).toHaveAttribute("data-release-id", target.releaseId);
  const saved = (await pool.query("select response_payload,status from activity_submissions where activity_assignment_id=$1", [assignment.id])).rows;
  assert.equal(saved.length, 1); assert.equal(saved[0].status, "awaiting_review");
  assert.equal(saved[0].response_payload.items[0].value, "Students Book final response");
  const output = process.env.PUBLISHED_BOOK_EVIDENCE_DIR || "/tmp/published-book-evidence";
  await studentPage.screenshot({ path: `${output}/students-book-submit-reload.png`, fullPage: true });
  await studentPage.close(); await unentitledContext.close(); await studentContext.close();
  await page.goto(`${origin}/#/teacher/assignments`);
  console.log("STUDENTS_BOOK_WORKFLOW class package, incompatible UI/API, entitlement separation, preview, Submit/reload and historical pin passed.");
}
